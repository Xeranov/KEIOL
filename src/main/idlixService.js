class IdlixService {
  constructor() {
    this.apiBase = IDLIX_API_BASE;
    this.referer = IDLIX_REFERER;
    this.cookiePath = this.getCookiePath();
    this.ensureSessionCookie();
    // In-memory cache for fast repeated queries
    this.cache = new Map();
    this.activeUnlocks = new Map();
  }

  getCookiePath() {
    let dir = os.tmpdir();
    if (electronApp && typeof electronApp.getPath === 'function') {
      try {
        dir = electronApp.getPath('userData');
      } catch {}
    }
    return path.join(dir, 'vidplayer_idlix_cookies.txt');
  }

  ensureSessionCookie() {
    try {
      if (!fs.existsSync(this.cookiePath) || fs.statSync(this.cookiePath).size < 50) {
        fs.writeFileSync(this.cookiePath, DEFAULT_ANON_COOKIES, 'utf8');
      }
    } catch (e) {
      console.warn('[Idlix] Could not initialize session cookie:', e.message);
    }
  }

  async refreshSession() {
    try {
      this.ensureSessionCookie();
      const res = await this.request('/auth/refresh?bootstrap=0', { method: 'POST' });
      if (res && res.user) {
        return res;
      }
    } catch (err) {
      console.warn('[Idlix] Session refresh notice:', err.message);
    }
    return null;
  }

  async ensureAuthenticatedSession() {
    try {
      const me = await this.getCurrentUser();
      if (me && (me.id || me.username)) {
        return true;
      }
      const refreshed = await this.refreshSession();
      if (refreshed && refreshed.user) {
        return true;
      }
      const loginRes = await this.login(ANON_CREDENTIALS.identifier, ANON_CREDENTIALS.password);
      if (loginRes && loginRes.success) {
        return true;
      }
    } catch (err) {
      console.warn('[Idlix] Session ensure error:', err.message);
    }
    return false;
  }

  /**
   * Execute request via curl.exe to preserve TLS fingerprint and handle session cookies.
   */
  request(endpoint, { method = 'GET', body = null, useCookies = true, timeoutMs = 15000, _isRetry = false } = {}) {
    return new Promise((resolve, reject) => {
      const url = endpoint.startsWith('http') ? endpoint : `${this.apiBase}${endpoint.startsWith('/') ? '' : '/'}${endpoint}`;
      const args = [
        '-s',
        '-L',
        '-m', String(Math.ceil(timeoutMs / 1000)),
        '-A', USER_AGENT,
        '-H', `Referer: ${this.referer}`,
        '-H', 'Accept: application/json, text/plain, */*',
        '-H', 'Accept-Language: id,en-US;q=0.9,en;q=0.8'
      ];

      if (useCookies) {
        args.push('-c', this.cookiePath);
        args.push('-b', this.cookiePath);
      }

      if (method === 'POST') {
        args.push('-X', 'POST');
        args.push('-H', 'Content-Type: application/json');
        if (body) {
          args.push('-d', typeof body === 'string' ? body : JSON.stringify(body));
        }
      }

      args.push(url);

      execFile('curl.exe', args, { maxBuffer: 10 * 1024 * 1024 }, async (err, stdout, stderr) => {
        if (err) {
          return reject(new Error(`Idlix request failed (${url}): ${err.message}`));
        }
        try {
          const json = JSON.parse(stdout);
          // If server reports access token expired and this isn't an auth request itself:
          if (json && json.error === 'Access token required' && !_isRetry && !endpoint.includes('/auth/')) {
            try {
              const ok = await this.ensureAuthenticatedSession();
              if (ok) {
                const retried = await this.request(endpoint, { method, body, useCookies, timeoutMs, _isRetry: true });
                return resolve(retried);
              }
            } catch (authErr) {
              console.warn('[Idlix] Auto-session recovery failed:', authErr.message);
            }
          }
          resolve(json);
        } catch (parseErr) {
          reject(new Error(`Failed to parse Idlix response: ${stdout.slice(0, 150)}`));
        }
      });
    });
  }

  /**
   * Fetch movies catalog with optional pagination and filters.
   */
  async getMovies({ page = 1, limit = 24, genre = '', country = '', year = '', quality = '', sort = '' } = {}) {
    const params = new URLSearchParams();
    if (page) params.set('page', String(page));
    if (limit) params.set('limit', String(limit));
    if (genre) params.set('genre', genre);
    if (country) params.set('country', country);
    if (year) params.set('year', String(year));
    if (quality) params.set('quality', quality);
    if (sort) params.set('sort', sort);

    const query = params.toString();
    const endpoint = `/movies${query ? '?' + query : ''}`;
    return await this.request(endpoint);
  }

  /**
   * Fetch TV series catalog with optional pagination and filters.
   */
  async getSeries({ page = 1, limit = 24, genre = '', country = '', year = '', sort = '' } = {}) {
    const params = new URLSearchParams();
    if (page) params.set('page', String(page));
    if (limit) params.set('limit', String(limit));
    if (genre) params.set('genre', genre);
    if (country) params.set('country', country);
    if (year) params.set('year', String(year));
    if (sort) params.set('sort', sort);

    const query = params.toString();
    const endpoint = `/series${query ? '?' + query : ''}`;
    return await this.request(endpoint);
  }

  /**
   * Fetch movie detail by slug.
   */
  async getMovieDetail(slug) {
    if (!slug) throw new Error('Movie slug is required');
    return await this.request(`/movies/${encodeURIComponent(slug)}`);
  }

  /**
   * Fetch series detail by slug (including seasons overview).
   */
  async getSeriesDetail(slug) {
    if (!slug) throw new Error('Series slug is required');
    return await this.request(`/series/${encodeURIComponent(slug)}`);
  }

  /**
   * Fetch episodes for a specific season of a TV series.
   */
  async getSeasonEpisodes(slug, seasonNumber = 1) {
    if (!slug) throw new Error('Series slug is required');
    return await this.request(`/series/${encodeURIComponent(slug)}/season/${seasonNumber}`);
  }

  /**
   * Search movies and series.
   */
  async search(query, type = '') {
    if (!query || !query.trim()) return { results: [], total: 0 };
    const params = new URLSearchParams({ q: query.trim() });
    if (type) params.set('type', type);
    return await this.request(`/search?${params.toString()}`);
  }

  /**
   * Get filter options (genres, countries, years, qualities).
   */
  async getFilterOptions(type = 'movies') {
    const target = type === 'series' ? 'series' : 'movies';
    const cacheKey = `filters_${target}`;
    if (this.cache.has(cacheKey)) {
      return this.cache.get(cacheKey);
    }
    const data = await this.request(`/${target}/filter-options`);
    this.cache.set(cacheKey, data);
    return data;
  }

  /**
   * Get trending & popular items from Idlix browse catalog.
   */
  async getTrending({ page = 1, limit = 30 } = {}) {
    const cacheKey = `trending_content_${page}_${limit}`;
    if (this.cache.has(cacheKey)) {
      const cached = this.cache.get(cacheKey);
      if (Date.now() - cached.timestamp < 10 * 60 * 1000) {
        return cached.data;
      }
    }
    try {
      // /browse?sort=popular returns trending movies and TV series
      const data = await this.request(`/browse?sort=popular&page=${page}&limit=${limit}`);
      if (data && Array.isArray(data.data) && data.data.length > 0) {
        this.cache.set(cacheKey, { timestamp: Date.now(), data });
        return data;
      }
      throw new Error('No browse popular data');
    } catch {
      // Fallback: fetch top viewed movies & series and combine
      try {
        const [popMovies, popSeries] = await Promise.all([
          this.getMovies({ page: 1, limit: Math.ceil(limit / 2), sort: 'views' }),
          this.getSeries({ page: 1, limit: Math.floor(limit / 2), sort: 'views' })
        ]);
        const combined = [
          ...(popMovies.data || []).map(m => ({ ...m, contentType: 'movie' })),
          ...(popSeries.data || []).map(s => ({ ...s, contentType: 'tv_series' }))
        ];
        const result = { data: combined, pagination: { page, limit, total: combined.length } };
        this.cache.set(cacheKey, { timestamp: Date.now(), data: result });
        return result;
      } catch (fallbackErr) {
        return await this.getMovies({ page: 1, limit, sort: 'views' });
      }
    }
  }

  /**
   * Step 1: Initiate streaming session and receive gateToken with unlockAt timestamp.
   * Can be invoked early (pre-unlock) when detail page opens or on hover.
   */
  async initiateStreamSession(contentType, contentId) {
    if (!contentType || !contentId) {
      throw new Error('contentType and contentId are required');
    }
    const cacheKey = `${contentType}:${contentId}`;
    const existing = this.activeUnlocks.get(cacheKey);
    if (existing && Date.now() < existing.expireTime) {
      return existing.data;
    }

    let playInfo = await this.request(`/watch/play-info/${contentType}/${contentId}`);
    if (playInfo && (playInfo.error === 'Access token required' || playInfo.viewerTier === 'guest')) {
      await this.ensureAuthenticatedSession();
      playInfo = await this.request(`/watch/play-info/${contentType}/${contentId}`);
    }
    if (playInfo && playInfo.error) {
      // Safe fallback: try without cookies as clean guest so playback never breaks
      playInfo = await this.request(`/watch/play-info/${contentType}/${contentId}`, { useCookies: false });
    }
    if (playInfo.error) {
      throw new Error(playInfo.error);
    }

    const unlockAt = playInfo.unlockAt || (Date.now() + 15000);
    const serverNow = playInfo.serverNow || Date.now();
    const waitMs = Math.max(0, unlockAt - serverNow);

    const sessionData = {
      contentType,
      contentId,
      gateToken: playInfo.gateToken,
      unlockAt,
      serverNow,
      waitMs,
      maxHeight: playInfo.maxHeight || 1080,
      countdownSec: playInfo.countdownSec || 7,
      startedAt: Date.now()
    };

    // Cache this active unlock for up to 5 minutes
    this.activeUnlocks.set(cacheKey, {
      data: sessionData,
      expireTime: Date.now() + 5 * 60 * 1000
    });

    return sessionData;
  }

  /**
   * Step 2: Claim unlocked session and redeem full HLS streaming playlist and subtitles.
   */
  async claimAndRedeemStream(gateToken, unlockAt = null) {
    if (!gateToken) throw new Error('gateToken is required');

    // If unlockAt is in the future, wait until unlock time + safety buffer
    if (unlockAt && Date.now() < unlockAt) {
      const remainingMs = Math.max(0, unlockAt - Date.now()) + 350;
      await new Promise(resolve => setTimeout(resolve, remainingMs));
    }

    let claimData = await this.request('/watch/session/claim', {
      method: 'POST',
      body: { gateToken }
    });

    // If server still indicates pending, wait for the specified remainingMs
    if (claimData.kind === 'pending' && claimData.remainingMs) {
      const extraWait = Math.max(250, claimData.remainingMs + 350);
      await new Promise(resolve => setTimeout(resolve, extraWait));
      claimData = await this.request('/watch/session/claim', {
        method: 'POST',
        body: { gateToken }
      });
    }

    if (!claimData || claimData.kind !== 'pentos' || !claimData.claim || !claimData.redeemUrl) {
      const errMsg = claimData?.error || 'Gagal klaim sesi streaming Pentos dari Idlix.';
      throw new Error(errMsg);
    }

    // Step 3: Redeem claim from streaming CDN
    const redeemData = await this.request(claimData.redeemUrl, {
      method: 'POST',
      body: {
        claim: claimData.claim,
        mode: 'browser'
      },
      useCookies: false
    });

    if (!redeemData || redeemData.code !== 'ok' || !redeemData.url) {
      throw new Error('Gagal redeem master playlist streaming dari CDN Majorplay.');
    }

    return {
      code: 'ok',
      streamUrl: redeemData.url,
      subtitles: Array.isArray(redeemData.subtitles) ? redeemData.subtitles : [],
      durationSec: claimData.durationSec || 0,
      title: claimData.title || '',
      maxHeight: claimData.maxHeight || 1080,
      qualityLadder: claimData.qualityLadder || [1080, 720],
      videoId: claimData.videoId || ''
    };
  }

  /**
   * Combined convenience helper: Initiates, waits if necessary, claims, and redeems.
   * On-progress callback can report remaining seconds for user countdown display.
   */
  async getStreamDirect(contentType, contentId, onCountdown = null) {
    const session = await this.initiateStreamSession(contentType, contentId);
    const targetUnlock = session.unlockAt;

    if (Date.now() < targetUnlock) {
      let remaining = Math.ceil((targetUnlock - Date.now()) / 1000);
      if (typeof onCountdown === 'function') onCountdown(remaining);

      while (Date.now() < targetUnlock) {
        await new Promise(r => setTimeout(r, 500));
        remaining = Math.max(0, Math.ceil((targetUnlock - Date.now()) / 1000));
        if (typeof onCountdown === 'function') onCountdown(remaining);
      }
    }

    return await this.claimAndRedeemStream(session.gateToken, targetUnlock);
  }

  /**
   * Log into Idlix account using identifier (username/email) and password.
   * Unlocks 1080p and 4K playback.
   */
  async login(identifier, password) {
    if (!identifier || !password) throw new Error('Username/email dan password harus diisi');
    const res = await this.request('/auth/login', {
      method: 'POST',
      body: { identifier, password }
    });
    if (res && res.error) {
      throw new Error(res.error);
    }
    this.cache.clear();
    const user = await this.getCurrentUser();
    return { success: true, user: user || res };
  }

  /**
   * Log out from Idlix account and reset session cookies.
   */
  async logout() {
    try {
      if (fs.existsSync(this.cookiePath)) {
        fs.unlinkSync(this.cookiePath);
      }
    } catch {}
    this.cache.clear();
    return { success: true };
  }

  /**
   * Get currently logged-in Idlix user profile.
   */
  async getCurrentUser() {
    try {
      const user = await this.request('/auth/me');
      if (user && !user.error && (user.id || user.username || user.email)) {
        return user;
      }
    } catch {}
    return null;
  }
}

module.exports = new IdlixService();

